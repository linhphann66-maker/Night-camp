import fs from 'node:fs';
import path from 'node:path';
import {extractNativeGrounds} from './lib/native-ground-source.mjs';
const root=path.resolve(import.meta.dirname,'..'),data=extractNativeGrounds(root);
// Generated, bounded data only. The editor/runtime never executes game source.
const text='// Generated by tools/build-native-ground.mjs from the archived original game. Do not hand-edit.\n'+`export const NATIVE_GROUND_BUILD=${JSON.stringify(data.build)};\nexport const NATIVE_GROUNDS=${JSON.stringify(data.grounds).replaceAll('<','\\u003c')};\nexport const NATIVE_MAPS=${JSON.stringify(data.maps).replaceAll('<','\\u003c')};\n`;
fs.writeFileSync(path.join(root,'dist/studio/maps/native-ground.mjs'),text);
console.log('Native ground:',Object.keys(data.grounds).length,'profiles,',Object.keys(data.maps).length,'source maps');
